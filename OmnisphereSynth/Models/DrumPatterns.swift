import Foundation

enum DrumFeel: String, CaseIterable {
    case ghost  = "Ghost"
    case pulse  = "Pulse"
    case ride   = "Ride"
    case crash  = "Crash"
    case toms   = "Toms"
    case hihat  = "HiHat"
    case build  = "Build"

    var emoji: String {
        switch self {
        case .ghost:  return "○"
        case .pulse:  return "◎"
        case .ride:   return "◉"
        case .crash:  return "✦"
        case .toms:   return "▣"
        case .hihat:  return "⊙"
        case .build:  return "▲"
        }
    }

    var description: String {
        switch self {
        case .ghost:  return "Sparse / minimal"
        case .pulse:  return "Half-time / slow"
        case .ride:   return "Ride bell driven"
        case .crash:  return "Crash accented"
        case .toms:   return "Tom driven"
        case .hihat:  return "Hi-hat groove"
        case .build:  return "Dense / intense"
        }
    }
}

enum DrumVoiceID: Int, CaseIterable {
    case kick = 0, snare, hihat, hihatOpen, rideBell, tomLo, tomMid, tomHi, crash

    var label: String {
        switch self {
        case .kick:      return "KICK"
        case .snare:     return "SNARE"
        case .hihat:     return "HH CL"
        case .hihatOpen: return "HH OP"
        case .rideBell:  return "RIDE"
        case .tomLo:     return "TOM L"
        case .tomMid:    return "TOM M"
        case .tomHi:     return "TOM H"
        case .crash:     return "CRASH"
        }
    }
}

struct DrumHit {
    let tick: Int32
    let voice: DrumVoiceID
    let velocity: Float
}

struct DrumPattern {
    let name: String
    let feel: DrumFeel
    let loopTicks: Int32
    let ticksPerBeat: Int32
    let hits: [DrumHit]

    var bars: Int { Int(loopTicks / (ticksPerBeat * 4)) }
}

extension DrumPattern {
    static let all: [DrumPattern] = drumPatternRaw.map { raw in
        DrumPattern(
            name: raw.0,
            feel: DrumFeel(rawValue: raw.1) ?? .build,
            loopTicks: Int32(raw.2),
            ticksPerBeat: Int32(raw.3),
            hits: raw.4.compactMap { tick, vi, vel in
                guard let v = DrumVoiceID(rawValue: vi) else { return nil }
                return DrumHit(tick: Int32(tick), voice: v, velocity: vel)
            }
        )
    }

    static func patterns(for feel: DrumFeel) -> [DrumPattern] {
        all.filter { $0.feel == feel }
    }
}

